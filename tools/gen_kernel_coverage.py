#!/usr/bin/env python3
"""Generate the backend kernel coverage table from Operator registrations."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "KERNEL_COVERAGE.md"

def registrations():
    result = {}
    for path in (ROOT / "src" / "operators").glob("*.cpp"):
        text = path.read_text(encoding="utf-8")
        for match in re.finditer(
            r"const Operator g_(\w+)_operator\s*=\s*\{(.*?)\n\};",
            text, re.S,
        ):
            name, body = match.groups()
            # The first four fields are name/infer/grad/ref; the next
            # initializer is the backend slot array.
            candidates = re.findall(r"\{([^{}]*)\}", body, re.S)
            candidates = [x for x in candidates if "ZNN_" in x or
                          re.match(r"\s*[^,]+,\s*[^,]+,\s*[^,]+,\s*[^,]+\s*$", x)]
            if not candidates:
                continue
            fields = [x.strip() for x in candidates[-1].split(",")]
            if len(fields) < 4:
                continue
            result[name] = {
                "CPU": fields[0] != "nullptr",
                "CUDA": "ZNN_CUDA_K(" in fields[1],
                "Metal": "ZNN_METAL_K(" in fields[2],
                "Vulkan": "ZNN_VULKAN_K(" in fields[3],
            }
    return result

def mark(value):
    return "✅" if value else "—"

def main():
    rows = registrations()
    lines = [
        "# Kernel coverage",
        "",
        "> Generated by `tools/gen_kernel_coverage.py`. A check means the operator registration has a native slot; a dash means the dispatcher may use the reported CPU fallback.",
        "",
        "| Operator | CPU | CUDA | Metal | Vulkan |",
        "|---|---:|---:|---:|---:|",
    ]
    for name in sorted(rows):
        row = rows[name]
        lines.append("| %s | %s | %s | %s | %s |" % (
            name, mark(row["CPU"]), mark(row["CUDA"]),
            mark(row["Metal"]), mark(row["Vulkan"])))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} operators)")

if __name__ == "__main__":
    main()
